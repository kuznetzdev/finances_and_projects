import {spawn} from 'node:child_process';
import {existsSync, mkdirSync} from 'node:fs';
import assert from 'node:assert/strict';
import {setTimeout as delay} from 'node:timers/promises';
import {chromium} from 'playwright-core';

const PORT=8765, HOST='http://127.0.0.1:'+PORT+'/';
const paths=['/usr/bin/google-chrome','/usr/bin/google-chrome-stable','/usr/bin/chromium','/opt/google/chrome/chrome'];
const binary=process.env.CHROME_BIN||paths.find(existsSync);
if(!binary)throw new Error('Browser is not installed on the runner');
mkdirSync('artifacts',{recursive:true});
const server=spawn('python3',['-m','http.server',String(PORT),'-d','site'],{stdio:'ignore'});
let browser;
try{
 let ok=false;
 for(let n=0;n<35;n++){
  try{const res=await fetch(HOST);if(res.ok){ok=true;break;}}catch{}
  await delay(150);
 }
 assert.ok(ok,'local static server did not start');
 browser=await chromium.launch({headless:true,executablePath:binary,args:['--no-sandbox','--disable-dev-shm-usage']});
 const context=await browser.newContext({viewport:{width:1440,height:1000}});
 const page=await context.newPage(),errors=[];
 page.on('pageerror',e=>{errors.push(e.message);console.error('DESKTOP PAGE ERROR',e.stack||e.message);});
 page.on('console',msg=>{if(msg.type()==='error')console.error('DESKTOP CONSOLE',msg.text());});
 const response=await page.goto(HOST+'?page=paradoxes',{waitUntil:'networkidle'});
 console.log('Desktop HTTP:',response?.status(),'URL:',page.url());
 await page.waitForTimeout(350);
 console.log('Desktop content preview:',(await page.locator('body').innerText()).slice(0,1100));
 await page.screenshot({path:'artifacts/paradoxes-debug.png',fullPage:true});
 if(errors.length)throw new Error('Page error before render: '+errors.join('; '));
 await page.locator('.paradox-row').first().waitFor({timeout:5000});
 assert.equal(await page.locator('.paradox-row').count(),30);
 assert.equal(await page.locator('#page-crumb').textContent(),'ПАРАДОКСЫ');
 assert.equal(await page.locator('#desktop-navigation [data-page="paradoxes"].selected').count(),1);
 await page.screenshot({path:'artifacts/paradoxes-desktop.png',fullPage:true});
 const search=page.locator('#paradox-search');
 await search.fill('МСФО');
 assert.equal(await page.locator('.paradox-row').count(),1);
 assert.equal(await search.evaluate(el=>document.activeElement===el),true,'search lost focus');
 await search.fill('');
 await page.locator('#paradox-seminar').selectOption('2');
 assert.equal(await page.locator('.paradox-row').count(),10);
 await page.locator('[data-paradox="s2-p1"]').click();
 assert.match(await page.locator('.paradox-question').innerText(),/рыночную премию/);
 await page.locator('#paradox-reveal').click();
 assert.equal(await page.locator('#paradox-done').isDisabled(),true);
 assert.match(await page.locator('.paradox-validity').innerText(),/Допущения и проверка данных/);
 assert.ok(await page.locator('.paradox-analysis p').count()>=2,'analysis should be split into readable paragraphs');
 await page.locator('#paradox-draft').fill('Нужно объяснить различие абсолютной и избыточной доходности. Бета умножается на премию за рыночный риск, а безрисковая ставка добавляется отдельно. Для актива с нулевой бетой ожидаемая доходность равна безрисковой, иначе возникло бы противоречие. Подстановка полной рыночной доходности неверно масштабирует вознаграждение за ожидание.');
 for(let i=0;i<3;i++)await page.locator('[data-check="'+i+'"]').check();
 assert.equal(await page.locator('#paradox-done').isEnabled(),true);
 await page.locator('#paradox-done').click();
 await page.locator('#paradox-back').click();
 assert.match(await page.locator('.paradox-summary').innerText(),/1 из 30/);
 await page.reload({waitUntil:'networkidle'});
 assert.match(await page.locator('.paradox-summary').innerText(),/1 из 30/);
 await page.locator('#theme-toggle').click();
 await page.screenshot({path:'artifacts/paradoxes-dark.png',fullPage:true});
 await page.goto(HOST+'?page=paradoxes&paradox=s1-p1',{waitUntil:'networkidle'});
 assert.equal(await page.locator('.paradox-detail').count(),1);
 assert.equal(await page.locator('#page-crumb').textContent(),'ПАРАДОКСЫ');
 await page.locator('#desktop-navigation [data-page="practice"]').click();
 assert.equal(await page.locator('.paradox-detail').count(),0);
 assert.equal(await page.locator('#desktop-navigation [data-page="practice"].selected').count(),1);
 assert.equal(await page.locator('#quick-random-exercise').count(),1);
 assert.equal(await page.locator('#random-task-bottom').count(),1);
 await page.goto(HOST+'?page=practice&topic=valuation&level=4&template=dcf-two-stage&seed=123',{waitUntil:'networkidle'});
 await page.setViewportSize({width:1440,height:260});
 await page.locator('.task-header').evaluate(el=>el.scrollIntoView({block:'start',behavior:'instant'}));
 await page.waitForTimeout(120);
 const shortcutMetrics=await page.evaluate(()=>{
  const rect=selector=>{const r=document.querySelector(selector).getBoundingClientRect();return {top:Math.round(r.top),bottom:Math.round(r.bottom)};};
  return {top:rect('#random-exercise'),actions:rect('.task-actions'),header:rect('.task-header'),scrollY,innerHeight,quickHidden:document.querySelector('#quick-random-exercise').hidden};
 });
 console.log('Desktop random shortcut visibility:',shortcutMetrics);
 assert.equal(await page.locator('#quick-random-exercise').isVisible(),true,'random shortcut should appear when reading a long task');
 // Keep the bottom action genuinely out of view while the answer field has focus.
 await page.locator('.fields').evaluate(el=>{el.style.paddingBottom='520px';});
 await page.locator('.field-group:not([hidden]) .answer-input').first().focus();
 // Focus may scroll back to the start; simulate a reader scrolling down while keeping that focus.
 await page.locator('.task-header').evaluate(el=>el.scrollIntoView({block:'start',behavior:'instant'}));
 await page.waitForTimeout(100);
 const focusedMetrics=await page.evaluate(()=>{
  const top=document.querySelector('#random-exercise').getBoundingClientRect();
  const bottom=document.querySelector('#random-task-bottom').getBoundingClientRect();
  return {topBottom:top.bottom,bottomTop:bottom.top,bottomBottom:bottom.bottom,viewHeight:innerHeight,scrollY,active:document.activeElement?.id,hidden:document.querySelector('#quick-random-exercise').hidden};
 });
 console.log('Desktop focused random shortcut:',focusedMetrics);
 assert.equal(await page.locator('#quick-random-exercise').isVisible(),true,'desktop random shortcut must remain available while the answer input is focused');
 const oldSerial=await page.locator('.task-serial').innerText();
 await page.locator('#quick-random-exercise').click();
 assert.notEqual(await page.locator('.task-serial').innerText(),oldSerial,'random shortcut should open a different task');
 await page.locator('#random-task-bottom').evaluate(el=>el.scrollIntoView({block:'center',behavior:'instant'}));
 await page.waitForTimeout(100);
 assert.equal(await page.locator('#quick-random-exercise').isVisible(),false,'float should hide when the footer shortcut is reachable');
 await context.close();
 const mobile=await browser.newContext({viewport:{width:360,height:780},isMobile:true,hasTouch:true});
 const mobilePage=await mobile.newPage();
 mobilePage.on('pageerror',e=>errors.push('mobile: '+e.message));
 await mobilePage.goto(HOST+'?page=paradoxes',{waitUntil:'networkidle'});
 assert.equal(await mobilePage.locator('.paradox-row').count(),30);
 assert.equal(await mobilePage.locator('#mobile-more-toggle.selected').count(),1);
 await mobilePage.locator('#mobile-more-toggle').click();
 assert.equal(await mobilePage.locator('#mobile-more-menu [data-page="paradoxes"]').isVisible(),true);
 await mobilePage.locator('#mobile-more-toggle').click();
 const widths=await mobilePage.evaluate(()=>({body:document.documentElement.scrollWidth,viewport:innerWidth}));
 assert.ok(widths.body<=widths.viewport+4,'horizontal page overflow '+JSON.stringify(widths));
 await mobilePage.screenshot({path:'artifacts/paradoxes-mobile.png',fullPage:true});
 await mobilePage.locator('[data-paradox="s1-p1"]').click();
 assert.equal(await mobilePage.locator('.paradox-question').isVisible(),true);
 await mobilePage.screenshot({path:'artifacts/paradoxes-mobile-detail.png',fullPage:true});
 await mobilePage.locator('#paradox-reveal').click();
 assert.equal(await mobilePage.locator('.paradox-answer').isVisible(),true);
 assert.equal(await mobilePage.locator('.paradox-validity').isVisible(),true);
 await mobilePage.locator('.mobile-navigation > [data-page="practice"]').click();
 assert.equal(await mobilePage.locator('#random-task-bottom').count(),1);
 await mobilePage.goto(HOST+'?page=practice&topic=valuation&level=4&template=dcf-two-stage&seed=123',{waitUntil:'networkidle'});
 await mobilePage.setViewportSize({width:360,height:260});
 await mobilePage.locator('.task-header').evaluate(el=>el.scrollIntoView({block:'start',behavior:'instant'}));
 await mobilePage.waitForTimeout(120);
 const mobileShortcutMetrics=await mobilePage.evaluate(()=>{
  const rect=selector=>{const r=document.querySelector(selector).getBoundingClientRect();return {top:Math.round(r.top),bottom:Math.round(r.bottom)};};
  return {top:rect('#random-exercise'),actions:rect('.task-actions'),header:rect('.task-header'),scrollY,innerHeight,quickHidden:document.querySelector('#quick-random-exercise').hidden,activeElement:document.activeElement.tagName};
 });
 console.log('Mobile random shortcut visibility:',mobileShortcutMetrics);
 assert.equal(await mobilePage.locator('#quick-random-exercise').isVisible(),true,'mobile random shortcut should sit above bottom navigation');
 const mobileSerial=await mobilePage.locator('.task-serial').innerText();
 await mobilePage.locator('#quick-random-exercise').click();
 assert.notEqual(await mobilePage.locator('.task-serial').innerText(),mobileSerial);
 await mobilePage.locator('#random-task-bottom').evaluate(el=>el.scrollIntoView({block:'center',behavior:'instant'}));
 await mobilePage.waitForTimeout(100);
 assert.equal(await mobilePage.locator('#quick-random-exercise').isVisible(),false,'floating shortcut should hide when mobile footer action is reachable');
 await mobile.close();
 assert.deepEqual(errors,[],'uncaught browser errors');
 console.log('PASS: paradox readability and data notes, random-task shortcuts, desktop/mobile, search, autosave and navigation.');
}finally{
 await browser?.close();
 server.kill('SIGTERM');
}
