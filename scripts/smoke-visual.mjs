import {spawn} from 'node:child_process';
import {existsSync,mkdirSync} from 'node:fs';
import assert from 'node:assert/strict';
import {setTimeout as delay} from 'node:timers/promises';
import {chromium} from 'playwright-core';

const PORT=8766,origin='http://127.0.0.1:'+PORT+'/';
const browserPath=process.env.CHROME_BIN||['/usr/bin/google-chrome','/usr/bin/google-chrome-stable','/usr/bin/chromium','/opt/google/chrome/chrome'].find(existsSync);
if(!browserPath)throw new Error('Chrome/Chromium not installed');
mkdirSync('artifacts',{recursive:true});
const server=spawn('python3',['-m','http.server',String(PORT),'-d','site'],{stdio:'ignore'});
let browser;
try{
 let live=false;
 for(let i=0;i<40;i++){try{if((await fetch(origin)).ok){live=true;break;}}catch{}await delay(150);}
 assert.ok(live,'Test server did not start');
 browser=await chromium.launch({headless:true,executablePath:browserPath,args:['--no-sandbox','--disable-dev-shm-usage']});
 const errors=[];
 const context=await browser.newContext({viewport:{width:1440,height:960}});
 const page=await context.newPage();
 page.on('pageerror',e=>errors.push(e.stack||e.message));
 page.on('console',m=>{if(m.type()==='error')errors.push('console: '+m.text());});
 await page.goto(origin+'?page=practice',{waitUntil:'networkidle'});
 assert.equal(await page.locator('.side-section-label').first().textContent(),'УЧЕБНЫЙ ПРОЦЕСС');
 assert.equal(await page.locator('#desktop-navigation .ui-icon').count(),6);
 assert.equal(await page.locator('.brand-mark .ui-icon').count(),1);
 assert.equal(await page.locator('#theme-toggle .ui-icon').count(),1);
 const iconValidity=await page.evaluate(()=>[...document.querySelectorAll('svg use')].every(x=>Boolean(document.getElementById(x.getAttribute('href')?.replace('#','')))));
 assert.ok(iconValidity,'Broken SVG symbol reference');
 await page.locator('#hint-btn').click();
 assert.equal(await page.locator('.hint-panel .hint-step').count(),2);
 assert.equal(await page.locator('.hint-heading .ui-icon').count(),1);
 await page.screenshot({path:'artifacts/visual-practice-hint.png',fullPage:true});
 await page.locator('[data-page="quiz"]').first().click();
 await page.locator('#quiz-hint-toggle').click();
 assert.equal(await page.locator('#quiz-hint-details').isVisible(),true);
 await page.screenshot({path:'artifacts/visual-quiz-hint.png',fullPage:true});
 await page.locator('[data-page="glossary"]').first().click();
 await page.locator('#glossary-search').fill('NPV');
 await page.locator('[data-term="npv"]').click();
 assert.ok(await page.locator('.glossary-formula-card').count()>0);
 assert.ok(await page.locator('.financial-formula').count()>0);
 assert.ok(await page.locator('.math-fraction').count()>0);
 const font=await page.locator('.page-intro h1').evaluate(x=>getComputedStyle(x).fontFamily);
 assert.ok(!font.toLowerCase().includes('georgia'),font);
 const sourceValid=await page.locator('.financial-formula').first().getAttribute('aria-label');
 assert.match(sourceValid,/NPV/);
 await page.screenshot({path:'artifacts/visual-glossary-formula.png',fullPage:true});
 await page.locator('#theme-toggle').click();
 await page.screenshot({path:'artifacts/visual-glossary-dark.png',fullPage:true});
 const width=await page.evaluate(()=>({doc:document.documentElement.scrollWidth,view:innerWidth}));
 assert.ok(width.doc<=width.view+3,'desktop overflow '+JSON.stringify(width));
 await page.goto(origin+'?page=practice&topic=valuation&level=4&template=dcf-two-stage&seed=123',{waitUntil:'networkidle'});
 assert.match(await page.locator('#content').innerText(),/Двухэтапный DCF/);
 await page.locator('#check-btn').click();
 await page.locator('#solution-btn').click();
 assert.equal(await page.locator('.solution-panel .financial-formula').count(),1);
 assert.ok(await page.locator('.solution-panel .math-sum').count()>0);
 assert.ok(await page.locator('.solution-panel .math-fraction').count()>0);
 await page.screenshot({path:'artifacts/visual-dcf-desktop.png',fullPage:true});
 await context.close();
 const mobile=await browser.newContext({viewport:{width:360,height:780},isMobile:true,hasTouch:true});
 const mob=await mobile.newPage();
 mob.on('pageerror',e=>errors.push('mobile: '+e.message));
 await mob.goto(origin+'?page=glossary',{waitUntil:'networkidle'});
 await mob.locator('#glossary-search').fill('NPV');
 await mob.locator('[data-term="npv"]').click();
 await mob.screenshot({path:'artifacts/visual-glossary-mobile.png',fullPage:true});
 const w=await mob.evaluate(()=>({doc:document.documentElement.scrollWidth,view:innerWidth,formulas:[...document.querySelectorAll('.glossary-formula-equation')].map(e=>({scroll:e.scrollWidth,client:e.clientWidth}))}));
 assert.ok(w.doc<=w.view+4,'mobile page overflow '+JSON.stringify(w));
 assert.ok(await mob.locator('.financial-formula').first().isVisible());
 await mob.locator('#mobile-navigation [data-page="practice"]').click();
 await mob.locator('#hint-btn').click();
 assert.equal(await mob.locator('.hint-panel .hint-step').count(),2);
 await mob.screenshot({path:'artifacts/visual-practice-mobile.png',fullPage:true});
 await mob.goto(origin+'?page=practice&topic=valuation&level=4&template=dcf-two-stage&seed=123',{waitUntil:'networkidle'});
 await mob.locator('#check-btn').click();
 await mob.locator('#solution-btn').click();
 assert.ok(await mob.locator('.solution-panel .math-sum').count()>0);
 const dcw=await mob.evaluate(()=>({page:document.documentElement.scrollWidth,screen:innerWidth,container:[...document.querySelectorAll('.solution-panel .glossary-formula-equation')].map(e=>({scroll:e.scrollWidth,visible:e.clientWidth}))}));
 assert.ok(dcw.page<=dcw.screen+4,'DCF mobile formula caused page overflow '+JSON.stringify(dcw));
 assert.ok(dcw.container[0]?.scroll>=dcw.container[0]?.visible,'formula scroll container missing');
 await mob.screenshot({path:'artifacts/visual-dcf-mobile.png',fullPage:true});
 await mobile.close();
 assert.deepEqual(errors,[],'browser errors');
 console.log('PASS: coherent SVG icons, accessible financial math, hints, typography, dark mode, mobile widths');
}finally{await browser?.close();server.kill('SIGTERM');}
