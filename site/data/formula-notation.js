const TOKEN=/^[\p{L}\p{N}_]$/u;
function boundary(expression,needle){
  const text=String(expression??'');let at=text.indexOf(needle);
  while(at!==-1){
    const prev=at>0?text[at-1]:'';
    const next=at+needle.length<text.length?text[at+needle.length]:'';
    if((!prev||!TOKEN.test(prev))&&(!next||!TOKEN.test(next)))return at;
    at=text.indexOf(needle,at+1);
  }
  return -1;
}
function eligible(record,id){return !record.ids || record.ids.includes(id);}
function meaningFor(entry,id){
  if(entry.symbol==='g'&&['ramsey','social-discount'].includes(id))return {...entry,meaning:'реальный долгосрочный темп роста потребления на душу населения',unit:'доля за период'};
  if(entry.symbol==='r'&&['loan-interest','annuity-payment','differential-payment'].includes(id))return {...entry,meaning:'ставка кредита за период в долях единицы',unit:'доля за период'};
  return entry;
}

/** List only symbols truly occurring in THIS expression; context disambiguates duplicate letters. */
export function symbolsForFormula(expression,id='',max=14){
  const found=[];
  for(const entry of specs){
    if(!eligible(entry,id))continue;
    const pos=boundary(expression,entry.symbol);
    if(pos<0)continue;
    // A specific context wins over the generic definition for the same symbol.
    const previous=found.findIndex(x=>x.symbol===entry.symbol);
    const candidate={...meaningFor(entry,id),position:pos};
    if(previous>=0){ if(entry.ids)found[previous]=candidate;continue; }
    found.push(candidate);
  }
  if(String(expression).includes('Σ')&&!found.some(x=>x.symbol==='Σ'))found.push({symbol:'Σ',meaning:'сумма по периодам',unit:'',position:String(expression).indexOf('Σ')});
  if(String(expression).includes('Δ')&&!found.some(x=>x.symbol==='Δ'))found.push({symbol:'Δ',meaning:'изменение показателя за период (конец − начало)',unit:'',position:String(expression).indexOf('Δ')});
  // Keep factors inside ratios and functions: E/V needs E and V, AF(r,n) needs r and n.
  found.sort((a,b)=>a.position-b.position || b.symbol.length-a.symbol.length);
  return found.slice(0,max).map(({position,ids,...x})=>x);
}

/** Extract names of variables explicitly present in the hint text, without revealing answers. */
export function symbolsForHint(hint,{topic='',title=''}={}){
  const text=String(hint??'');
  let id='';
  const context=(title+' '+text).toLocaleLowerCase('ru');
  if(/рамсе|социальн.*ставк/.test(context))id='ramsey';
  else if(/привилегированн.*wacc/i.test(context))id='wacc';
  else if(/wacc|структур.*капитал/i.test(context))id='wacc';
  else if(/гордон|дивиденд.*рост/i.test(context))id='gordon';
  else if(/колл[- ]опцион/i.test(context))id='call-option';
  else if(/пут[- ]опцион/i.test(context))id='put-option';
  else if(/процент.*кредит|начислен.*процент/i.test(context))id='loan-interest';
  else if(/погашен.*долг/i.test(context))id='differential-payment';
  else if(/ltv.*клиент/i.test(context))id='ltv-customer';
  else if(/yield.*to|дюрац|облигац/i.test(context))id='ytm';
  else if(/eac|eaa/i.test(context))id='eac';
  else if(/fcff/i.test(context))id='fcff';
  else if(/fcfe/i.test(context))id='fcfe';
  else if(/npv|срок.*окупаемост/i.test(context))id='npv';
  else if(/capm|бета|beta/i.test(context))id='capm';
  else if(/dso|dio|dpo|оборачиваемост/i.test(context))id='dso';
  else if(topic==='tax')id='profit-tax';
  const result=symbolsForFormula(text,id,10);
  // Only show notation that is actually used in the hint. No irrelevant global glossary dump.
  return result;
}

