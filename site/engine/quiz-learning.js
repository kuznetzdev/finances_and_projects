export function hintForConcept(concept) {
 return TERM_HINTS[concept.group] ?? 'Сначала определите, какой результат описан: сумма денег, ставка, коэффициент, период или метод. Сравните единицы измерения вариантов.';
}

function relatedOperationOptions(correct, allAnswers, seed) {
 const family=OPERATION_FAMILIES.find(items=>items.includes(correct)) ?? [];
 const candidates=[...new Set([...family,...allAnswers].filter(item=>item!==correct))];
 // Вначале выбираем конкурирующие понятия только из того же класса, а не из соседнего блока.
 const relatives=shuffle(family.filter(item=>item!==correct),rng(seed)).slice(0,3);
 const others=candidates.filter(item=>!relatives.includes(item));
 return shuffle([correct,...relatives,...shuffle(others,rng(seed+17)).slice(0,3-relatives.length)],rng(seed+739));
}

export function buildOperationQuiz(operation, allOperations, seed) {
 const answers=[...new Set(allOperations.map(op=>op.answer))];
 return {
  kind:'operations', id:operation.id, scenario:operation.event,
  question:operationQuestionLabel(operation.answer),
  answer:operation.answer, why:operation.why,
  hint:operation.hint || hintForOperation(operation.answer),
  options:relatedOperationOptions(operation.answer,answers,seed)
 };
}

export function buildConceptQuiz(concept, allConcepts, seed) {
 const distractors=[...allConcepts.filter(x=>x.id!==concept.id&&x.group===concept.group), ...allConcepts.filter(x=>x.id!==concept.id&&x.group!==concept.group)];
 const unique=[...new Set(distractors.map(x=>x.term))];
 const peers=shuffle(unique.slice(0, Math.max(3,allConcepts.filter(x=>x.group===concept.group).length-1)),rng(seed)).slice(0,3);
 const remaining=unique.filter(x=>!peers.includes(x));
 const choices=shuffle([concept.term,...peers,...shuffle(remaining,rng(seed+2)).slice(0,3-peers.length)],rng(seed+739));
 return {
  kind:'terms',id:concept.id,scenario:concept.definition,
  question:'Как называется описанное финансовое понятие?',
  answer:concept.term,why:concept.contrast,hint:hintForConcept(concept),options:choices
 };
}

export function describeQuizAnswer(quiz, selected, concepts) {
 const correctExpansion=abbreviationFor(quiz.answer);
 if(quiz.kind==='operations')return {
   reason:quiz.why.length<45?`${quiz.why} Важно различать отражение операции в отчётности и момент фактического денежного платежа.`:quiz.why,
   rule:CLASSIFICATION_NOTES[quiz.answer] || 'Классифицируйте событие по его экономическому содержанию и моменту признания.',
   wrong:selected!==quiz.answer ? CLASSIFICATION_NOTES[selected] || 'Этот вариант описывает другую характеристику финансовой операции.' : '',
   expansion:correctExpansion
 };
 const correct=concepts.find(c=>c.term===quiz.answer);
 const distractor=concepts.find(c=>c.term===selected);
 return {
   reason:correct?.definition || quiz.scenario,
   rule:correct?.contrast || quiz.why,
   wrong:selected!==quiz.answer && distractor ? `«${distractor.term}» означает: ${distractor.definition} ${distractor.contrast}` : '',
   expansion:correctExpansion
 };
}

export function explainAlternative(option, quiz, concepts) {
 if(quiz.kind==='operations')return CLASSIFICATION_NOTES[option] || 'Сверьте предмет и период этой классификации с событием в условии.';
 const entry=concepts.find(c=>c.term===option);
 const a=abbreviationFor(option);
 return `${entry?.definition||'Сопоставьте определение с исходным условием.'}${a?` Расшифровка: ${a.english} — ${a.russian}.`:''}`;
}